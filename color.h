/// @brief 按字符串选择色阶函数，未匹配或为空时使用传入的默认色阶
inline std::function<cv::Vec3b(double, const RenderConfig&)> pick_color(
    const std::string& scheme, cv::Vec3b (*deflt)(double, const RenderConfig&)) {
    std::string s;
    s.resize(scheme.size());
    std::transform(scheme.begin(), scheme.end(), s.begin(),
                   [] (unsigned char c) { return static_cast<char>(std::tolower(c)); });
    if (s == "ca")
        return color_ir_ca;
    if (s == "plasma")
        return color_plasma;
    if (s == "vis")
        return color_enhanced_vis;
    if (s == "refsb")
        return color_refsb;
    return deflt;
}

