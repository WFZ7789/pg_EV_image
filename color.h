[[nodiscard]] inline uint8_t get_linear_gray(float val, float l, float h) noexcept {
    float norm = std::clamp((val - l) / (h - l), 0.0f, 1.0f);
    return static_cast<uint8_t>(norm * 255.0f);
}

[[nodiscard]] inline cv::Vec3b color_brtemp(double val, const RenderConfig& cfg) noexcept {
    uchar g = get_linear_gray(static_cast<float>(val), cfg.hival, cfg.lowval);
    return {g, g, g};
}

[[nodiscard]] inline cv::Vec3b color_refsb(double val, const RenderConfig& cfg) noexcept {
    uchar g = get_linear_gray(static_cast<float>(val), cfg.lowval, cfg.hival);
    return {g, g, g};
}

