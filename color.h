inline cv::Vec3b color_rbtop_wv(double val, const RenderConfig& cfg) {
    double epct = (val - cfg.lowval) / (cfg.hival - cfg.lowval);
    epct = std::clamp(epct, 0.0, 1.0);
    epct *= 0.84;

    auto lerp = [] (double t, double x0, double x1, double y0, double y1) {
        return y0 + (y1 - y0) * (t - x0) / (x1 - x0);
    };

    constexpr double WV_BR = 73.0 / 255, WV_BG = 96.0 / 255, WV_BB = 137.0 / 255;
    constexpr double WV_LR = 110.0 / 255, WV_LG = 215.0 / 255, WV_LB = 166.0 / 255;
    constexpr double WV_DR = 43.0 / 255, WV_DG = 72.0 / 255, WV_DB = 63.0 / 255;

    double r = 0.0, g = 0.0, b = 0.0;

    if (epct < 0.190476) r = lerp(epct, 0.0, 0.190476, 1.0, 0.0);
    else if (epct < 0.269841) r = lerp(epct, 0.190476, 0.269841, 0.0, 1.0);
    else if (epct < 0.349206) r = 1.0;
    else if (epct < 0.428571) r = lerp(epct, 0.349206, 0.428571, 1.0, WV_LR);
    else if (epct < 0.500000) r = lerp(epct, 0.428571, 0.500000, WV_LR, WV_BR);
    else if (epct < 0.580000) r = lerp(epct, 0.500000, 0.580000, WV_BR, WV_DR);
    else if (epct < 0.619048) r = WV_DR;
    else if (epct < 0.658730) r = lerp(epct, 0.619048, 0.658730, WV_DR, 0.980392);
    else if (epct < 0.840000) r = lerp(epct, 0.658730, 0.840000, 0.980392, 0.0);
    else r = 0.0;

    if (epct < 0.190476) g = lerp(epct, 0.0, 0.190476, 1.0, 0.0);
    else if (epct < 0.269841) g = 0.0;
    else if (epct < 0.349206) g = lerp(epct, 0.269841, 0.349206, 0.0, 1.0);
    else if (epct < 0.428571) g = lerp(epct, 0.349206, 0.428571, 1.0, WV_LG);
    else if (epct < 0.500000) g = lerp(epct, 0.428571, 0.500000, WV_LG, WV_BG);
    else if (epct < 0.580000) g = lerp(epct, 0.500000, 0.580000, WV_BG, WV_DG);
    else if (epct < 0.619048) g = WV_DG;
    else if (epct < 0.658730) g = lerp(epct, 0.619048, 0.658730, WV_DG, 0.980392);
    else if (epct < 0.840000) g = lerp(epct, 0.658730, 0.840000, 0.980392, 0.0);
    else g = 0.0;

    if (epct < 0.190476) b = lerp(epct, 0.0, 0.190476, 1.0, 0.0);
    else if (epct < 0.349206) b = 0.0;
    else if (epct < 0.428571) b = lerp(epct, 0.349206, 0.428571, 0.0, WV_LB);
    else if (epct < 0.500000) b = lerp(epct, 0.428571, 0.500000, WV_LB, WV_BB);
    else if (epct < 0.580000) b = lerp(epct, 0.500000, 0.580000, WV_BB, WV_DB);
    else if (epct < 0.619048) b = WV_DB;
    else if (epct < 0.658730) b = lerp(epct, 0.619048, 0.658730, WV_DB, 0.980392);
    else if (epct < 0.840000) b = lerp(epct, 0.658730, 0.840000, 0.980392, 0.0);
    else b = 0.0;

    return cv::Vec3b(
        static_cast<uchar>(std::clamp(b * 255.0, 0.0, 255.0)),
        static_cast<uchar>(std::clamp(g * 255.0, 0.0, 255.0)),
        static_cast<uchar>(std::clamp(r * 255.0, 0.0, 255.0))
    );
}

